/**
 * 轻量 i18n：中文为 key，英文查表；切换语言时 Compose 自动重组。
 * 早期版本直接写死中文字面量，这里集中管理，避免每处再包一层 Context。
 */
object L10n {
    var lang by mutableStateOf("zh")
        private set

    private const val PREFS = "lumen_lang"
    private const val KEY = "mode"

    fun init(ctx: Context) {
        val mode = ctx.getSharedPreferences(PREFS, Context.MODE_PRIVATE).getString(KEY, "system") ?: "system"
        lang = resolve(mode, ctx.resources.configuration.locales[0])
    }

    fun setMode(ctx: Context, mode: String) {
        ctx.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit().putString(KEY, mode).apply()
        lang = resolve(mode, Locale.getDefault())
    }

    fun mode(ctx: Context): String =
        ctx.getSharedPreferences(PREFS, Context.MODE_PRIVATE).getString(KEY, "system") ?: "system"

    private fun resolve(mode: String, locale: java.util.Locale): String = when (mode) {
        "zh" -> "zh"
        "en" -> "en"
        else -> if (locale.language == "zh") "zh" else "en"
    }

    /** 静态文案：英文缺失时回退中文。 */
    fun t(zh: String): String = if (lang == "en") EN[zh] ?: zh else zh

    /** 带插值的文案：调用方分别给出中英文完整句子。 */
    fun tf(zh: String, en: String): String = if (lang == "en") en else zh

